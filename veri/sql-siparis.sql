create table if not exists public.siparisler (
  id          bigint generated by default as identity primary key,
  siparis_no  text not null,                          -- TT-YYYYAAGG-XXXX; havale açıklamasına bu yazılır
  paket       text not null,                          -- fiyat-motoru.js paket id (sgs-donem, kgk, ...)
  paket_ad    text,
  tutar       integer not null check (tutar between 100 and 50000),
  ad_soyad    text not null,
  email       text not null,
  telefon     text,
  adres       text,                                   -- fatura adresi
  fatura      jsonb,                                  -- {tip:bireysel|kurumsal, tckn|unvan+vkn+vd}
  odeme       text not null default 'havale',
  durum       text not null default 'odeme_bekliyor', -- odeme_bekliyor | odendi | iptal | iade
  kvkk_onay   timestamptz not null default now(),     -- onay kutusu zorunlu; kayıt anı
  olusturma   timestamptz not null default now()
);

create index if not exists siparisler_durum_idx on public.siparisler (durum, olusturma desc);
create index if not exists siparisler_no_idx    on public.siparisler (siparis_no);
create index if not exists siparisler_mail_idx  on public.siparisler (email);

alter table public.siparisler enable row level security;

