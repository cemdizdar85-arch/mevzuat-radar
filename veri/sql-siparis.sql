--  aynı kapıyı burada yeniden açmanın anlamı yok.
--
--  Sipariş formu giriş yapmamış ziyaretçiye hizmet ettiği için anonim yazma
--  KALKAMAZ. Onun yerine yazılabilecek şeyin BİÇİMİ kilitleniyor: form ne
--  gönderiyorsa yalnız o geçer.
--
--  ⚠️ DÜRÜST SINIR: bu bir hız sınırı DEĞİLDİR. Formu taklit eden kararlı bir
--  bot hâlâ geçerli görünen satır basabilir. Gerçek hız sınırı için istemcinin
--  IP'sini SUNUCUNUN görmesi gerekir (Edge Function) ya da Turnstile/captcha
--  konmalıdır — ikisi de kart altyapısıyla birlikte gelecek. Buradaki kilit
--  gelişigüzel/otomatik çöpü eler ve asıl işi yapar: aşağıdaki durum kilidi.
-- ============================================================================

drop policy if exists siparisler_ekle on public.siparisler;
create policy siparisler_ekle
  on public.siparisler for insert
  to anon, authenticated
  with check (
    -- 1) DURUM KİLİDİ (en önemlisi): dışarıdan gelen sipariş HER ZAMAN
    --    'odeme_bekliyor' doğar. Bu olmasaydı biri kendi siparişini 'odendi'
    --    yazıp gönderebilir, sen ödenmişler listesine bakıp erişim açabilirdin.
    --    Ödendi damgasını YALNIZ sen vurursun (panel = service_role, RLS'siz).
        durum = 'odeme_bekliyor'
    and odeme = 'havale'

    -- 2) Sipariş no formu ne üretiyorsa o: TT-YYYYAAGG-XXXX
    --    (satin-al.html · siparisNo(); harf havuzu ACDEFHJKLMNPRTUVXYZ2345679)
    and siparis_no ~ '^TT-[0-9]{8}-[ACDEFHJKLMNPRTUVXYZ2345679]{4}$'

    -- 3) E-posta biçimi (formdaki regex'in eşi)
    and email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'

    -- 4) Alan boyu tavanları — dev gövde yollayıp depoyu şişirmeyi engeller
    and length(ad_soyad) between 3 and 100
    and length(email)    <= 160
    and length(coalesce(telefon, '')) <= 30
    and length(coalesce(adres, ''))   between 0 and 500
    and length(coalesce(paket_ad, '')) <= 120
    and length(paket) <= 40
    and pg_column_size(coalesce(fatura, '{}'::jsonb)) <= 2000
  );

-- Okuma/güncelleme/silme politikası BİLEREK YOK:
-- RLS açık + select policy yok = kimse başkasının siparişini/adresini göremez.
-- (Sipariş listesi yalnız service_role ile, yani Supabase panelinden okunur.)
-- Ayrıca tablo seviyesinde de kapatalım — politika unutulsa bile kapı kapalı:
revoke select, update, delete on public.siparisler from anon, authenticated;

